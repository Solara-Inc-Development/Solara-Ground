pub fn push_rect_px(
    out: &mut Vec<UiVertex>,
    screen_w: f32,
    screen_h: f32,
    rect_px: [f32; 4],
    color: [u8; 4],
) {
    let [x, y, w, h] = rect_px;
    let x0 = (x / screen_w) * 2.0 - 1.0;
    let x1 = ((x + w) / screen_w) * 2.0 - 1.0;
    let y0 = 1.0 - (y / screen_h) * 2.0;
    let y1 = 1.0 - ((y + h) / screen_h) * 2.0;

    let v0 = UiVertex {
        pos_ndc: [x0, y1],
        color,
    };
    let v1 = UiVertex {
        pos_ndc: [x1, y1],
        color,
    };
    let v2 = UiVertex {
        pos_ndc: [x1, y0],
        color,
    };
    let v3 = UiVertex {
        pos_ndc: [x0, y0],
        color,
    };
    out.extend_from_slice(&[v0, v1, v2, v0, v2, v3]);
}

/// Renders crisp pixel-art ASCII text at `(x, y)` with pixel scale `scale` and 1px drop shadow.
pub fn push_text_px(
    out: &mut Vec<UiVertex>,
    screen: (f32, f32),
    origin_px: (f32, f32),
    scale: f32,
    text: &str,
    color: [u8; 4],
) {
    let (sw, sh) = screen;
    let (mut cx, cy) = origin_px;
    let shadow = [12, 14, 18, (u16::from(color[3]) * 3 / 4) as u8];

    for ch in text.chars() {
        let rows = glyph_5x7(ch);
        for (ry, &bits) in rows.iter().enumerate() {
            if bits == 0 {
                continue;
            }
            let mut col = 0usize;
            while col < 5 {
                if ((bits >> (4 - col)) & 1) == 0 {
                    col += 1;
                    continue;
                }
                let mut run = 1usize;
                while col + run < 5 && ((bits >> (4 - (col + run))) & 1) != 0 {
                    run += 1;
                }
                let px = cx + (col as f32) * scale;
                let py = cy + (ry as f32) * scale;
                let pw = (run as f32) * scale;
                push_rect_px(
                    out,
                    sw,
                    sh,
                    [px + scale * 0.5, py + scale * 0.5, pw, scale],
                    shadow,
                );
                push_rect_px(out, sw, sh, [px, py, pw, scale], color);
                col += run;
            }
        }
        cx += 6.0 * scale;
    }
}
